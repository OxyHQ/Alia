import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import type { ConfigContext, ExpoConfig } from 'expo/config';
import { oxySplashScreenPlugin } from '@oxy.so/expo-splash/config';

/**
 * Keep push credentials out of the repository while preserving local native
 * development. EAS file secrets expose a temporary path through the named
 * environment variable; local builds may use the ignored conventional file.
 * Without either file, Android still supports local notifications but does not
 * configure FCM push delivery.
 */
export default ({ config }: ConfigContext): ExpoConfig => {
  const googleServicesFile = process.env.GOOGLE_SERVICES_JSON?.trim() || './google-services.json';
  const android = { ...config.android };
  const plugins = [...(config.plugins ?? [])];

  // Keep the two Oxy splash entries adjacent and immediately after the router:
  // the shared branding plugin augments the native resources generated by
  // expo-splash-screen. Alia's supplied foreground asset has more transparent
  // padding than Mention's mark, so 212dp gives both visible symbols the same
  // on-device footprint while staying inside Android 12's safe circle.
  const splashPlugins: NonNullable<ExpoConfig['plugins']> = [
    oxySplashScreenPlugin({
      image: './assets/icon-512-maskable.png',
      imageWidth: 212,
    }),
    '@oxy.so/expo-splash',
  ];
  const routerIndex = plugins.findIndex(
    (plugin) => plugin === 'expo-router' || (Array.isArray(plugin) && plugin[0] === 'expo-router'),
  );
  plugins.splice(routerIndex >= 0 ? routerIndex + 1 : 0, 0, ...splashPlugins);

  // `@expo/config-types` 58.0.3 does not declare the flag yet; the CLI reads it.
  const experiments: ExpoConfig['experiments'] & { noxcturnalTransformWorker?: boolean } = {
    ...config.experiments,
    // Expo's oxc transformer, about 2x faster cold bundles than Babel. Development
    // only: in a production export it keeps the requires of dead platform branches
    // (`if (Platform.OS !== 'web') require(...)`), pulling native-only packages into
    // the web bundle. The CLI sets NODE_ENV before it reads this config.
    noxcturnalTransformWorker: process.env.NODE_ENV !== 'production',
  };

  if (existsSync(resolve(__dirname, googleServicesFile))) {
    android.googleServicesFile = googleServicesFile;
  } else {
    delete android.googleServicesFile;
  }

  return {
    ...config,
    name: config.name ?? 'Alia',
    slug: config.slug ?? 'alia',
    android,
    plugins,
    experiments,
  };
};
