#!/usr/bin/env bun
/**
 * Draws Alia's still — the picture `AliaAvatarIcon` shows wherever she is not moving — and
 * writes it to `src/lib/alia-avatar-still.generated.ts` as a `data:` URI.
 *
 *     bun run render:avatar-still        (from packages/alia-chat)
 *
 * The icon must not boot the 3D runtime just to sit in a header at 20 px (measured: 31 requests,
 * 16.1 MiB from alia.onl on a cold load, a rendered still exactly like a live avatar). So her
 * still is made here, once, by the very runtime the live avatar uses — the installed
 * `@oxy.so/bloom`'s `assets/character-runtime`, served locally — drawn exactly as Bloom's still
 * pipeline draws one (`renderWebStill`: a paused portrait, reduced motion) and read back as PNG.
 *
 * Run it again when `ALIA_AVATAR` changes (a test fails until you do) or when a Bloom upgrade
 * changes how the runtime draws her.
 *
 * Needs a Chromium for `playwright-core` (`bunx playwright install chromium`).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createServer } from 'node:http';
import type { AddressInfo } from 'node:net';
import { dirname, extname, join, normalize, resolve } from 'node:path';
import { chromium } from 'playwright-core';
import { ALIA_AVATAR } from '../src/lib/alia-character';

/** CSS px of the square, at 2x: covers every icon size up to 64 px, crisp on a 3x phone at 20. */
const CSS_SIZE = 64;
const DEVICE_SCALE = 2;
const OUTPUT = resolve(import.meta.dir, '../src/lib/alia-avatar-still.generated.ts');

const bloomRoot = dirname(require.resolve('@oxy.so/bloom/package.json'));
const bloomVersion: string = JSON.parse(
  readFileSync(join(bloomRoot, 'package.json'), 'utf8'),
).version;
const runtimeDir =
  process.env.BLOOM_AVATAR_RUNTIME_DIR ?? join(bloomRoot, 'assets', 'character-runtime');
const runtimeRevision = createHash('sha256')
  .update(readFileSync(join(runtimeDir, 'manifest.json')))
  .digest('hex');
// Bloom resolves a character before it hands it to the runtime; so does this.
const { resolveAvatarCharacter } = await import(join(bloomRoot, 'src/agent-avatar/character.ts'));
const character = resolveAvatarCharacter(ALIA_AVATAR);

const TYPES: Record<string, string> = {
  '.mjs': 'text/javascript',
  '.js': 'text/javascript',
  '.json': 'application/json',
  '.bin': 'application/octet-stream',
  '.png': 'image/png',
};
const PAGE = `<!doctype html><html><body style="margin:0;background:transparent">
<canvas id="c" style="width:${CSS_SIZE}px;height:${CSS_SIZE}px;display:block"></canvas></body></html>`;

const server = createServer((request, response) => {
  const path = normalize(decodeURIComponent(new URL(request.url ?? '/', 'http://x').pathname));
  if (path === '/') {
    response.writeHead(200, { 'content-type': 'text/html' }).end(PAGE);
    return;
  }
  try {
    const file = readFileSync(join(runtimeDir, path.replace(/^\/bloom-character\//, '')));
    response.writeHead(200, { 'content-type': TYPES[extname(path)] ?? 'application/octet-stream' });
    response.end(file);
  } catch {
    response.writeHead(404).end();
  }
}).listen(0);
const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;

const browser = await chromium.launch({
  executablePath: process.env.CHROME_PATH,
  args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'],
});
try {
  const page = await browser.newPage({
    viewport: { width: CSS_SIZE, height: CSS_SIZE },
    deviceScaleFactor: DEVICE_SCALE,
  });
  await page.goto(`${origin}/`);
  const uri = await page.evaluate(
    async ({ runtimeUrl, character }) => {
      const canvas = document.getElementById('c') as HTMLCanvasElement;
      const runtime = await import(runtimeUrl);
      await new Promise<void>((ready, failed) => {
        runtime
          .createAvatar(
            canvas,
            { character, paused: true, portrait: true, reduced: true },
            { onReady: ready, onError: () => failed(new Error('the runtime could not draw her')) },
          )
          .catch(failed);
      });
      return canvas.toDataURL('image/png');
    },
    { runtimeUrl: `${origin}/bloom-character/runtime.mjs`, character },
  );
  if (!uri.startsWith('data:image/png;base64,')) throw new Error('no PNG came back');
  const bytes = Buffer.from(uri.slice('data:image/png;base64,'.length), 'base64').length;
  writeFileSync(
    OUTPUT,
    `// Generated by \`bun run render:avatar-still\` (scripts/render-avatar-still.ts). Do not edit.

/**
 * Alia's still: \`ALIA_AVATAR\` drawn by @oxy.so/bloom ${bloomVersion}'s character runtime as Bloom
 * runtime manifest ${runtimeRevision}. It draws a paused portrait with reduced motion, ${CSS_SIZE} px at ${DEVICE_SCALE}x, ${bytes} bytes of PNG.
 */
export const ALIA_AVATAR_STILL = '${uri}';

/** The character it was drawn from; a test holds it equal to \`ALIA_AVATAR\`. */
export const ALIA_AVATAR_STILL_OF = ${JSON.stringify(ALIA_AVATAR)};
`,
  );
  console.log(`Alia's still: ${bytes} bytes of PNG -> ${OUTPUT}`);
} finally {
  await browser.close();
  server.close();
}
